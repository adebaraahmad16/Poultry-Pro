import assert from 'node:assert/strict';
import { expireSession, handleUnauthorized } from '../sessionService.js';
const values = new Map();
globalThis.localStorage = {getItem:key=>values.get(key) ?? null,setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
const events = [];
globalThis.window = {dispatchEvent:event=>events.push(event)};
values.set('poultrypro_user','original user'); values.set('poultrypro_flocks','original records');
values.set('poultrypro_token','expired');values.set('poultrypro_is_logged_in','true');
handleUnauthorized({status:401},{Authorization:'Bearer expired'});
assert.equal(values.has('poultrypro_token'),false);
assert.equal(values.get('poultrypro_is_logged_in'),'false');
assert.equal(events[0].type,'farmer_session_expired');
assert.equal(values.get('poultrypro_user'),'original user');
assert.equal(values.get('poultrypro_flocks'),'original records');
values.set('poultrypro_token','new-session');
handleUnauthorized({status:401},{Authorization:'Bearer old-session'});
assert.equal(values.get('poultrypro_token'),'new-session');
